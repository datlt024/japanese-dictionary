// Inline to keep this module dependency-free (avoids webpack bundle issues)
function katakanaToHiragana(text: string): string {
    return text.replace(/[ァ-ヶ]/g, (ch) =>
        String.fromCharCode(ch.charCodeAt(0) - 0x60)
    )
}

