export function deinflectKeyword(input: string): string[] {
    const normalized = katakanaToHiragana(input)
    const candidates = new Set<string>()

    for (const [suffix, replacements] of RULES) {
        if (!normalized.endsWith(suffix)) continue

        const stem = normalized.slice(0, -suffix.length)

        // Single-char suffixes (て/た) require a non-empty stem to avoid
        // generating pointless single-word candidates from bare て/た.
        if (suffix.length === 1 && stem.length === 0) continue

        for (const replacement of replacements) {
            const candidate = stem + replacement
            if (candidate !== normalized && candidate.length >= 2) {
                candidates.add(candidate)
            }
        }
    }

    return Array.from(candidates)
}
